#!/usr/bin/env python3
"""Writes one review sheet per language from the suite JSON.

Usage (from the repository root):
    python3 acceptance/render_review.py

Each sheet lists every visitor message in that language with its English intent
and the expected language effect, so a reviewer who reads that language can
check meaning, tone and naturalness without reading the JSON.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SUITE = HERE / "visitor-heldout" / "v0.1"
OUT = SUITE / "review"
NAMES = {"en": "English", "es": "Spanish", "zh-CN": "Simplified Chinese", "ko": "Korean"}
TITLES = {"aic-28560": "The Bedroom", "aic-11723": "Woman at Her Toilette"}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def effect(e, override=None):
    parts = [f"reply in **{e['answer_language']}**"]
    if e.get("preference_after") not in (None, "auto"):
        parts.append(f"saved preference {e['preference_after']}")
    if override:
        parts.append(f"selector set to {override}")
    return "; ".join(parts)


def main():
    single = json.loads((SUITE / "single-turn.json").read_text(encoding="utf-8"))
    multi = json.loads((SUITE / "multi-turn.json").read_text(encoding="utf-8"))
    OUT.mkdir(exist_ok=True)
    for lang, name in NAMES.items():
        lines = [
            f"# {name} review sheet",
            "",
            f"Generated from `single-turn.json` and `multi-turn.json` (suite {single['version']}). "
            "Do not edit this file by hand; change the JSON and run `python3 acceptance/render_review.py`.",
            "",
            "For each row, check that the message reads like something a real visitor would say, that it means the "
            "same as the English intent, and that any language instruction in it has the stated effect. Mark the "
            "row OK, or write the corrected wording in the Notes column.",
            "",
            "## Single-turn scenarios",
            "",
            "| ID | Artwork | Visitor message | Intended meaning | Expected | OK / notes |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for s in single["scenarios"]:
            v = next(x for x in s["variants"] if x["language"] == lang)
            lines.append(f"| {s['id']} | {TITLES[s['artwork_id']]} | {cell(v['text'])} | {cell(s['intent'])} | "
                         f"{effect(v['expect'], v['language_override'])} | |")
        lines += ["", "## Multi-turn turns in this language", "",
                  "Turns marked `und` are neutral acknowledgements or pure language/translation commands. Their "
                  "reply language comes from the conversation state, as the Expected column shows.", "",
                  "| Script | Turn | Visitor message | Expected | OK / notes |", "| --- | --- | --- | --- | --- |"]
        count = 0
        for sc in multi["scripts"]:
            for t in sc["steps"]:
                if t["kind"] != "message":
                    continue
                if t["language"] == lang or (t["language"] == "und" and _looks(t["text"], lang)):
                    count += 1
                    tag = " (und)" if t["language"] == "und" else ""
                    lines.append(f"| {sc['id']} | {t['visitor_turn']}{tag} | {cell(t['text'])} | "
                                 f"{effect(t['expect'], t['language_override'])} | |")
        lines += ["", "## Reviewer sign-off", "", "| Reviewer | Relationship to the language | Date | Rows changed |",
                  "| --- | --- | --- | --- |", "| | | | |", ""]
        (OUT / f"{lang}.md").write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {(OUT / f'{lang}.md').relative_to(HERE.parent)} ({len(single['scenarios'])} + {count} rows)")


def _looks(text, lang):
    """Script of a neutral message, so it appears on the right reviewer's sheet."""
    if any("\uac00" <= ch <= "\ud7af" for ch in text):
        return lang == "ko"
    if any("\u4e00" <= ch <= "\u9fff" for ch in text):
        return lang == "zh-CN"
    spanish = any(ch in text for ch in "¿¡ñáéíóú«»") or text.split()[0].strip(".,!").lower() in {
        "vale", "gracias", "perfecto", "muchas", "traduce", "solo", "a", "en"}
    if spanish:
        return lang == "es"
    return lang == "en"


if __name__ == "__main__":
    main()
